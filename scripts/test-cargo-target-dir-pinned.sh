#!/usr/bin/env bash
# AMUX-3667. A bare `cargo` in this checkout must NOT build into ./target.
#
# CLAUDE.md mandates one shared build dir and gives the measured reason (~37
# per-session trees at 10-15 GB took this volume to 741 MB free). The mandate
# was a CONVENTION with nothing enforcing it, and on 2026-08-24 the checkout
# held 23 GB of debug artifacts: gitignored so `git status` could not show it,
# outside the disk ranking's candidate roots so the disk report could not name
# it, and cargo silent because ./target is its default and correct behaviour.
# Three instruments, none able to express it.
#
# `install.sh` now writes `.cargo/config.toml` pinning `[build] target-dir`.
# This asserts the property that file exists for, and — the half that matters —
# that pinning it did NOT take away the overrides the e2e worktree build and CI
# depend on. `build.target-dir` is the lowest of cargo's three precedences;
# verified here rather than read off a doc.
#
# Runs `cargo metadata`, not a build: it resolves the same config and costs a
# second.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1

pass=0; fail=0
ok()   { printf '  ok   — %s\n' "$1"; pass=$((pass+1)); }
bad()  { printf '  FAIL — %s\n' "$1"; fail=$((fail+1)); }

target_dir() {
  # `env -u` so an exported CARGO_TARGET_DIR in the caller's shell — which is
  # the normal state for a lane following CLAUDE.md — cannot mask the very
  # default this test exists to check. Without it the assertion passes for the
  # wrong reason and the file becomes theatre.
  env -u CARGO_TARGET_DIR "$@" cargo metadata --no-deps --format-version 1 2>/dev/null \
    | python3 -c 'import json,sys; print(json.load(sys.stdin)["target_directory"])'
}

if [[ ! -f .cargo/config.toml ]]; then
  echo "cargo-target-dir: SKIPPED — .cargo/config.toml absent."
  echo "  It is generated by ./install.sh and gitignored (absolute, machine-specific)."
  echo "  A fresh clone that has not run install.sh legitimately has no pin yet, so this"
  echo "  is a skip rather than a failure. Run ./install.sh to enable it."
  exit 0
fi

RESOLVED="$(target_dir)"
case "$RESOLVED" in
  "$ROOT"/target|"$ROOT"/target/)
    bad "a bare cargo still builds into the checkout: $RESOLVED" ;;
  "")
    bad "cargo metadata produced no target_directory — the probe is broken, not the config" ;;
  *)
    ok "a bare cargo builds outside the checkout ($RESOLVED)" ;;
esac

# CONTROL, and the reason this file is not just one assertion: pinning must not
# remove the override. serve-head.sh:167 exports CARGO_TARGET_DIR for the e2e
# HEAD worktree precisely because sharing the fleet's dir let worktree dep-info
# poison repo builds into silent no-ops (AMUX-2961), and CI sets
# $GITHUB_WORKSPACE/target. If the pin won over the env, both would break in a
# way that looks like a flaky build rather than a config change.
OVERRIDE="/private/tmp/amux-3667-override-check"
GOT="$(CARGO_TARGET_DIR="$OVERRIDE" cargo metadata --no-deps --format-version 1 2>/dev/null \
       | python3 -c 'import json,sys; print(json.load(sys.stdin)["target_directory"])')"
if [[ "$GOT" == "$OVERRIDE" ]]; then
  ok "CARGO_TARGET_DIR still overrides the pin (serve-head + CI keep their dirs)"
else
  bad "the pin beat CARGO_TARGET_DIR — e2e worktree and CI would silently move: got $GOT"
fi

printf 'cargo-target-dir: %d passed, %d failed\n' "$pass" "$fail"
[[ "$fail" -eq 0 ]]
