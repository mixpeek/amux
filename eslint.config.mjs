// eslint flat config — scoped to the dashboard SPA (crates/amux-dashboard/static).
//
// Purpose: the no-silent-actions static gate. Two silent-dead-handler bugs
// shipped in one week (schedule delete, then worker delete 2026-08-09) — both
// were an undefined name inside an async handler, so the rejection vanished and
// the UI did nothing. `no-undef` catches that class at lint time; the runtime
// unhandledrejection toast in app.js is the floor, this gate is the ceiling.
//
// Only high-signal correctness rules — this is a gate, not a style linter.
// Run it via: scripts/spa-lint.sh (regenerates the globals allowlist first).
import fs from 'node:fs';
import globals from 'globals';

// Generated by scripts/gen-spa-globals.mjs from the actual code (top-level
// declarations in static/*.js + index.html inline scripts + window.X= exports).
// The SPA is classic-script: hundreds of top-level names are its cross-script
// API surface, so they are globals by construction, not by hand-listing.
let generated = {};
try {
  generated = JSON.parse(fs.readFileSync(
    new URL('./crates/amux-dashboard/eslint.globals.generated.json', import.meta.url), 'utf8'));
} catch (e) {
  // spa-lint.sh always regenerates before linting; a direct `eslint` run
  // without the file should fail loudly on no-undef rather than silently
  // passing, so an empty fallback is correct here.
}

// Vendor globals from the CDN <script src=> tags in index.html — hand-listed
// because they are not in our source; each entry names its tag.
const vendorGlobals = {
  Papa: 'readonly',          // papaparse
  marked: 'readonly',        // marked
  DOMPurify: 'readonly',     // dompurify
  Sortable: 'readonly',      // sortablejs
  Quill: 'readonly',         // quill
  QuillMarkdown: 'readonly', // quilljs-markdown
  Chart: 'readonly',         // chart.js
  Motion: 'readonly',        // motion.dev
  GridStack: 'readonly',     // gridstack
  Terminal: 'readonly',      // @xterm/xterm
  FitAddon: 'readonly',      // @xterm/addon-fit
  WebLinksAddon: 'readonly', // @xterm/addon-web-links
  hljs: 'readonly',          // highlight.js
  XLSX: 'readonly',          // sheetjs (xlsx) — Excel/ODS viewer, loaded on demand
  L: 'readonly',             // leaflet (+ markercluster)
  FullCalendar: 'readonly',  // fullcalendar
  posthog: 'readonly',       // posthog snippet (index.html inline bootstrap)
};

const gateRules = {
  // THE rule this gate exists for: an undefined name in a handler dies as an
  // invisible rejected promise (worker-delete bug, 2026-08-09).
  'no-undef': 'error',
  // vars:'local' — top-level functions are the HTML onclick API surface, they
  // are legitimately "unused" inside app.js itself. caughtErrors:'none' —
  // `catch(e) {}` with unused e is the file's idiom for optional paths.
  'no-unused-vars': ['warn', { vars: 'local', args: 'after-used', caughtErrors: 'none' }],
  'no-dupe-keys': 'error',
  // A SECOND `function foo()` at top level silently replaces the first — the
  // last declaration wins in a classic script, and nothing anywhere says so.
  // Found three live in app.js (2026-08-13): _fmtBytes, _fmtDur, and timeAgo.
  // timeAgo is why this is an error and not a warning — the surviving copy had
  // lost the earlier one's falsy guard, so every caller without a timestamp
  // rendered "NaNd ago" (undefined) or "20679d ago" (null/0) on screen.
  //
  // The class is worse than its symptoms: editing the shadowed copy changes
  // NOTHING, so the natural debugging loop is "my fix does not work", against
  // code that reads correctly. no-dupe-keys was already here for the object
  // case; this is the same defect for functions.
  //
  // builtinGlobals:false is REQUIRED, not incidental. This SPA is a classic
  // script whose top-level names are its cross-file API, and spa-lint.sh
  // regenerates them into the globals allowlist every run — so with the default
  // (true) the rule flags every top-level declaration as redeclaring "a built-in
  // global", ~700 false errors that bury the 3 real ones.
  'no-redeclare': ['error', { builtinGlobals: false }],
  'no-unreachable': 'error',
  // checkLoops:false — while(true) polling loops are intentional in an SPA.
  'no-constant-condition': ['error', { checkLoops: false }],
};

export default [
  {
    // Page scripts: app.js and any future classic-script split.
    files: ['crates/amux-dashboard/static/*.js'],
    ignores: ['crates/amux-dashboard/static/sw.js'],
    languageOptions: {
      ecmaVersion: 2024,
      sourceType: 'script',
      globals: { ...globals.browser, ...vendorGlobals, ...generated },
    },
    rules: gateRules,
  },
  {
    // Service worker: worker scope, not page scope.
    files: ['crates/amux-dashboard/static/sw.js'],
    languageOptions: {
      ecmaVersion: 2024,
      sourceType: 'script',
      globals: { ...globals.serviceworker },
    },
    rules: gateRules,
  },
];
